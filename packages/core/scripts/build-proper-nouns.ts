function addToken(
  raw: string,
  names: Set<string>,
  commonEnglish: Set<string>,
  skipGeneric: boolean,
) {
  const text = raw.normalize("NFC").trim();
  if (!text) return;
  for (const part of text.split(/[\s_/]+/)) {
    const cleaned = part
      .replace(/^[^\p{L}]+/gu, "")
      .replace(/[^\p{L}\p{N}'’-]+$/gu, "");
    if (cleaned.length < 2) continue;
    const key = cleaned.toLowerCase();
    if (commonEnglish.has(key)) continue;
    if (skipGeneric && GENERIC_PLACE_TOKENS.has(key)) continue;
    names.add(key);
    if (!key.includes("-")) continue;
    for (const bit of key.split("-")) {
      if (bit.length < 2) continue;
      if (commonEnglish.has(bit)) continue;
      if (skipGeneric && GENERIC_PLACE_TOKENS.has(bit)) continue;
      names.add(bit);
    }
  }
}

function generatedHeader(comment: "//" | "///"): string {
  return `${comment} Generated by packages/core/scripts/build-proper-nouns.ts. Do not edit.\n`;
}

async function fetchText(url: string): Promise<string> {
  const response = await fetch(url);
  if (!response.ok) {
    throw new Error(`${url} failed: ${response.status}`);
  }
  return response.text();
}

function linesFromText(text: string): string[] {
  return text.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);
}

const commonEnglish = new Set<string>();
for (const word of linesFromText(
  await fetchText(
    "https://raw.githubusercontent.com/powerlanguage/word-lists/master/1000-most-common-words.txt",
  ),
)) {
  commonEnglish.add(word.toLowerCase());
}
const commonJson = JSON.parse(
  await fetchText(
    "https://raw.githubusercontent.com/dariusk/corpora/master/data/words/common.json",
  ),
) as { commonWords?: unknown };
if (!Array.isArray(commonJson.commonWords)) {
  throw new Error("common.json was missing commonWords");
}
for (const word of commonJson.commonWords) {
  if (typeof word === "string") commonEnglish.add(word.toLowerCase());
}

const sortedCommon = [...commonEnglish].sort((a, b) => a.localeCompare(b));
const tsWords = sortedCommon.map((word) => `  ${JSON.stringify(word)},`).join("\n");
await Bun.write(
  COMMON_ENGLISH_TS_PATH,
  `${generatedHeader("//")}
export const COMMON_ENGLISH_WORDS: ReadonlySet<string> = new Set([
${tsWords}
]);
`,
);
const swiftWords = sortedCommon
  .map((word) => `        "${word.replaceAll("\\", "\\\\").replaceAll("\"", "\\\"")}",`)
  .join("\n");
await Bun.write(
  COMMON_ENGLISH_SWIFT_PATH,
  `${generatedHeader("///")}
enum CommonEnglishWords {
    static let words: Set<String> = [
${swiftWords}
    ]
}
`,
);
console.log(`Wrote ${sortedCommon.length} common English words`);

const names = new Set<string>();

const firstNamesJson = JSON.parse(
  await fetchText(
    "https://raw.githubusercontent.com/dominictarr/random-name/master/first-names.json",
  ),
) as unknown;
if (!Array.isArray(firstNamesJson)) {
  throw new Error("first-names.json was not an array");
}
for (const name of firstNamesJson) {
  if (typeof name === "string") addToken(name, names, commonEnglish, false);
}

for (const name of linesFromText(
  await fetchText(
    "https://raw.githubusercontent.com/smashew/NameDatabases/master/NamesDatabases/first%20names/us.txt",
  ),
)) {
  addToken(name, names, commonEnglish, false);
}

for (const name of linesFromText(
  await fetchText(
    "https://raw.githubusercontent.com/smashew/NameDatabases/master/NamesDatabases/surnames/us.txt",
  ),
)) {
  addToken(name, names, commonEnglish, false);
}

const countries = JSON.parse(
  await fetchText(
    "https://cdn.jsdelivr.net/npm/world-countries@5.1.0/countries.json",
  ),
) as Array<{
  name?: { common?: string; official?: string };
  capital?: string[];
  altSpellings?: string[];
}>;

for (const country of countries) {
  if (country.name?.common) addToken(country.name.common, names, commonEnglish, true);
  if (country.name?.official) addToken(country.name.official, names, commonEnglish, true);
  for (const capital of country.capital ?? []) {
    addToken(capital, names, commonEnglish, true);
  }
  for (const spelling of country.altSpellings ?? []) {
    addToken(spelling, names, commonEnglish, true);
  }
}

for (const state of US_STATES) addToken(state, names, commonEnglish, true);

const sorted = [...names].sort((a, b) => a.localeCompare(b));
const payload = { version: 1, names: sorted };
await Bun.write(GAZETTEER_PATH, `${JSON.stringify(payload)}\n`);
console.log(`Wrote ${sorted.length} names to ${GAZETTEER_PATH.pathname}`);
